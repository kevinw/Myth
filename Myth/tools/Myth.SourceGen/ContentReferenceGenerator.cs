using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Myth.SourceGen;

// Static ContentRef<T> properties are the source of truth for dependencies selected by code
// defaults. Authored actor overrides are collected separately from resolved room/prefab JSON.
[Generator]
public sealed class ContentReferenceGenerator : IIncrementalGenerator
{
#pragma warning disable RS2008 // Internal game diagnostic; this analyzer is not a versioned package.
	static readonly DiagnosticDescriptor InlineDefault = new(
		"MYTH001",
		"Content reference default is not registered",
		"Content reference default must use a static ContentRef<> field or property",
		"Myth.Content",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true,
		description: "Static typed references are generated into Content.pak dependency collection.");
#pragma warning restore RS2008

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var references = context.SyntaxProvider.CreateSyntaxProvider(
			predicate: static (node, _) => node is PropertyDeclarationSyntax or VariableDeclaratorSyntax,
			transform: static (ctx, _) => StaticContentReference(ctx))
			.Where(static name => name != null)
			.Collect();
		var invalidDefaults = context.SyntaxProvider.CreateSyntaxProvider(
			predicate: static (node, _) => node is PropertyDeclarationSyntax or VariableDeclaratorSyntax,
			transform: static (ctx, _) => InvalidInstanceDefault(ctx))
			.Where(static diagnostic => diagnostic != null);

		context.RegisterSourceOutput(references, static (spc, names) =>
		{
			var sb = new StringBuilder();
			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("namespace Myth;");
			sb.AppendLine();
			sb.AppendLine("static class GeneratedContentReferences");
			sb.AppendLine("{");
			sb.AppendLine("\tpublic static void Collect(global::Myth.ContentDependencyCollector collector)");
			sb.AppendLine("\t{");
			foreach (var name in names.Where(static name => name != null).Distinct().OrderBy(static name => name, System.StringComparer.Ordinal))
				sb.AppendLine($"\t\tcollector.Add({name}, \"code default {name}\");");
			sb.AppendLine("\t}");
			sb.AppendLine("}");
			spc.AddSource("GeneratedContentReferences.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
		});
		context.RegisterSourceOutput(invalidDefaults, static (spc, diagnostic) => spc.ReportDiagnostic(diagnostic!));
	}

	static string? StaticContentReference(GeneratorSyntaxContext context)
	{
		var symbol = DeclaredSymbol(context);
		if (symbol == null || !symbol.IsStatic || !AccessibleToGeneratedCode(symbol) ||
			symbol.ContainingType.TypeParameters.Length != 0 || !IsContentReference(MemberType(symbol)))
			return null;
		return $"{symbol.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}.{symbol.Name}";
	}

	static Diagnostic? InvalidInstanceDefault(GeneratorSyntaxContext context)
	{
		var symbol = DeclaredSymbol(context);
		if (symbol == null || symbol.IsStatic || symbol.DeclaredAccessibility != Accessibility.Public ||
			!IsContentReference(MemberType(symbol)) || Initializer(context.Node) is not { } initializer ||
			IsRegisteredDefault(context.SemanticModel, initializer))
			return null;
		return Diagnostic.Create(InlineDefault, initializer.GetLocation());
	}

	static ISymbol? DeclaredSymbol(GeneratorSyntaxContext context) => context.Node switch
	{
		PropertyDeclarationSyntax property => context.SemanticModel.GetDeclaredSymbol(property),
		VariableDeclaratorSyntax variable when variable.Parent?.Parent is FieldDeclarationSyntax =>
			context.SemanticModel.GetDeclaredSymbol(variable),
		_ => null,
	};

	static ITypeSymbol? MemberType(ISymbol symbol) => symbol switch
	{
		IPropertySymbol property => property.Type,
		IFieldSymbol field => field.Type,
		_ => null,
	};

	static ExpressionSyntax? Initializer(SyntaxNode node) => node switch
	{
		PropertyDeclarationSyntax property => property.Initializer?.Value,
		VariableDeclaratorSyntax variable => variable.Initializer?.Value,
		_ => null,
	};

	static bool IsRegisteredDefault(SemanticModel model, ExpressionSyntax expression)
	{
		if (expression.IsKind(SyntaxKind.DefaultLiteralExpression) || expression is DefaultExpressionSyntax)
			return true;
		if (model.GetConstantValue(expression) is { HasValue: true, Value: "" })
			return true;
		if (expression is BaseObjectCreationExpressionSyntax creation && creation.ArgumentList?.Arguments.Count == 1 &&
			model.GetConstantValue(creation.ArgumentList.Arguments[0].Expression) is { HasValue: true, Value: "" })
			return true;
		return model.GetSymbolInfo(expression).Symbol is { IsStatic: true } symbol &&
			AccessibleToGeneratedCode(symbol) && symbol.ContainingType.TypeParameters.Length == 0 &&
			IsContentReference(MemberType(symbol));
	}

	static bool AccessibleToGeneratedCode(ISymbol symbol)
		=> symbol.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal;

	static bool IsContentReference(ITypeSymbol? type)
		=> type is INamedTypeSymbol { Name: "ContentRef", Arity: 1 } named &&
			named.ContainingNamespace.ToDisplayString() == "Myth";
}

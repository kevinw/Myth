using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Myth.SourceGen;

// Emits Myth.GeneratedActors.RegisterAll(), one Factory.Register<T>() call per type
// carrying [GameActor]. ForAttributeWithMetadataName pre-filters to just those types, so
// this re-runs only when a [GameActor]-bearing class changes (cheap under dotnet watch).
[Generator]
public sealed class ActorRegistrationGenerator : IIncrementalGenerator
{
	const string AttributeFullName = "Myth.GameActorAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var actors = context.SyntaxProvider.ForAttributeWithMetadataName(
				AttributeFullName,
				predicate: static (_, _) => true,
				transform: static (ctx, _) => ctx.TargetSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
			.Collect();

		context.RegisterSourceOutput(actors, static (spc, names) =>
		{
			var sb = new StringBuilder();
			sb.AppendLine("// <auto-generated/>");
			sb.AppendLine("namespace Myth;");
			sb.AppendLine();
			sb.AppendLine("static class GeneratedActors");
			sb.AppendLine("{");
			sb.AppendLine("\tpublic static void RegisterAll()");
			sb.AppendLine("\t{");
			foreach (var name in names.Distinct().OrderBy(n => n, System.StringComparer.Ordinal))
				sb.AppendLine($"\t\tFactory.Register<{name}>();");
			sb.AppendLine("\t}");
			sb.AppendLine();
			sb.AppendLine("\tpublic static void RegisterActorSpecs()");
			sb.AppendLine("\t{");
			foreach (var name in names.Distinct().OrderBy(n => n, System.StringComparer.Ordinal))
				sb.AppendLine($"\t\tFactory.RegisterActorSpec<{name}>();");
			sb.AppendLine("\t}");
			sb.AppendLine("}");
			spc.AddSource("GeneratedActors.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
		});
	}
}

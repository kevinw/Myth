using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Myth.SourceGen;

// Collects compile-time event paths without making builds depend on FMOD Studio.
[Generator]
public sealed class AudioEventGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var events = context.SyntaxProvider.CreateSyntaxProvider(
				static (node, _) => node is InvocationExpressionSyntax { ArgumentList.Arguments.Count: > 0 },
				static (ctx, _) => GetAudioEventPath(ctx))
			.Where(static path => path != null)
			.Collect();

		context.RegisterSourceOutput(events, static (spc, paths) =>
		{
			var source = new StringBuilder();
			source.AppendLine("// <auto-generated/>");
			source.AppendLine("namespace Myth;");
			source.AppendLine();
			source.AppendLine("static class GeneratedAudioEvents");
			source.AppendLine("{");
			source.AppendLine("\tpublic static readonly string[] Paths =");
			source.AppendLine("\t[");
			foreach (var path in paths.Distinct().OrderBy(path => path, System.StringComparer.Ordinal))
				source.AppendLine($"\t\t{SymbolDisplay.FormatLiteral(path!, quote: true)},");
			source.AppendLine("\t];");
			source.AppendLine("}");
			spc.AddSource("GeneratedAudioEvents.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
		});
	}

	static string? GetAudioEventPath(GeneratorSyntaxContext context)
	{
		var invocation = (InvocationExpressionSyntax)context.Node;
		if (context.SemanticModel.GetSymbolInfo(invocation).Symbol is not IMethodSymbol method || !IsAudioEventMethod(method))
			return null;

		var constant = context.SemanticModel.GetConstantValue(invocation.ArgumentList.Arguments[0].Expression);
		return constant is { HasValue: true, Value: string path } && path.Length > 0 ? path : null;
	}

	static bool IsAudioEventMethod(IMethodSymbol method)
		=> method.Name switch
		{
			"PlayAudioEvent" or "CreateAudioEvent" => method.ContainingType.ToDisplayString() == "Myth.Game",
			"AudioEvent" or "AudioEventDebounced" => method.ContainingType.ToDisplayString() == "Myth.Actor",
			"MenuAudioEvent" => method.ContainingType.ToDisplayString() == "Myth.Manager",
			_ => false,
		};
}
